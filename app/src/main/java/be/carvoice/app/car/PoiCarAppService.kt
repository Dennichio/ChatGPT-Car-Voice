package be.carvoice.app.car

import android.content.Intent
import android.content.pm.ApplicationInfo
import androidx.car.app.CarAppService
import androidx.car.app.Screen
import androidx.car.app.Session
import androidx.car.app.validation.HostValidator
import be.carvoice.app.R

/** A genuine destination finder; route guidance belongs to the selected navigation app. */
class CarVoiceService : CarAppService() {
    override fun createHostValidator(): HostValidator =
        if (applicationInfo.flags and ApplicationInfo.FLAG_DEBUGGABLE != 0) {
            HostValidator.ALLOW_ALL_HOSTS_VALIDATOR
        } else {
            HostValidator.Builder(applicationContext)
                .addAllowedHosts(R.array.car_hosts_allowlist)
                .build()
        }

    override fun onCreateSession(): Session = PoiSession()
}

private class PoiSession : Session() {
    override fun onCreateScreen(intent: Intent): Screen = PoiSearchScreen(carContext)
}
